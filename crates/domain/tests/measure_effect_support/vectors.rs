#[test]
fn no_measure_change_has_an_independent_utf8_golden_vector() {
    let outcome = MeasureDecisionOutcome::new(MeasureDecisionOutcomeInput::NoMeasureChange(note(
        "N\u{e9}",
    )))
    .unwrap();
    assert_eq!(
        hex(&outcome.canonical_bytes()),
        "4d4546583101000000034ec3a9"
    );
}

#[test]
fn every_effect_tag_and_two_to_two_substitution_have_an_independent_golden_vector() {
    let outcome = changes(mixed());
    assert_eq!(outcome.canonical_bytes().len(), 764);
    assert_eq!(hex(&outcome.canonical_bytes()), MIXED_HEX);
}
